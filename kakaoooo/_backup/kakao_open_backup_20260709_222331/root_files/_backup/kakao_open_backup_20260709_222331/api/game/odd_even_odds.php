<?php
/**
 * 홀짝 정답 확률 (웹·info2·mutual 공통)
 *
 * $홀짝_확률모드 — 아래 한 줄만 바꾸면 전 경로 동일 적용
 *   'easy' : 이지모드 (기본 48.5:48.5, 무 3% 고정, 홀/짝 흔들림 ±6%p)
 *   'hard' : 하드모드 (기본 46:46, 무 8% 고정, 홀/짝 흔들림 ±12%p · 패배 배수 +1)
 */
if (!isset($홀짝_확률모드)) {
  $홀짝_확률모드 = 'easy';
}

if (!function_exists('홀짝_정답_선정')) {
  /**
   * @param string|null $모드 null이면 전역 $홀짝_확률모드 사용
   * @return int 1=홀 2=짝 3=무
   */
  function 홀짝_정답_선정($모드 = null) {
    global $홀짝_확률모드;
    if ($모드 === null) {
      $모드 = $홀짝_확률모드;
    }
    $모드 = strtolower(trim((string)$모드));
    if ($모드 !== 'hard') {
      $모드 = 'easy';
    }

    if ($모드 === 'hard') {
      $무고정 = 80;
      $홀기본 = (int)((1000 - $무고정) / 2);
      $유동폭 = 120;
    } else {
      $무고정 = 30;
      $홀기본 = 485;
      $유동폭 = 60;
    }

    $홀기준 = $홀기본 + random_int(-$유동폭, $유동폭);
    $짝기준 = 1000 - $무고정 - $홀기준;

    $정답주사위 = random_int(1, 1000);
    if ($정답주사위 <= $홀기준) {
      return 1;
    }
    if ($정답주사위 <= $홀기준 + $짝기준) {
      return 2;
    }
    return 3;
  }
}
