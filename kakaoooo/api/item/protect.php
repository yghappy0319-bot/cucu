<?php
// 마법 .보호 (info2.php · enchant 웹 공용)
// 한도 1회당 보호 지급: 일반 60% N~N×2 · 크리 40% N~N×3
// 필요 변수: $두자리닉넴, $정보, $내무기, $내강화, $단위, $쿨타임, $대상닉, $요청보호횟수
// ※ 마법 .시전·.보호 한도는 magic_used 공용 (한도 외 없음)

$보호입력대상 = trim((string)($대상닉 ?? ''));
$요청보호횟수 = isset($요청보호횟수) ? max(1, (int)$요청보호횟수) : 1;
$시전자닉 = trim((string)($두자리닉넴 ?? ''));
if ($시전자닉 === '' && isset($정보) && is_array($정보)) {
  $시전자닉 = trim((string)($정보['name'] ?? ''));
}

if ($보호입력대상 === '') {
  // .보호 → 랜덤 대상 (본인 포함)
  $랜덤행 = db_select("SELECT name FROM tb_member WHERE status = 0 ORDER BY RAND() LIMIT 1");
  $대상닉 = $랜덤행 ? trim($랜덤행['name'] ?? '') : '';
  if ($대상닉 === '') {
    시전_채팅응답('❌ 보호할 대상 회원이 없어요.');
  }
} else {
  // .보호 닉 → 지정 대상 (본인 닉이면 본인)
  $두글자 = (function_exists('getTwoCharNick') ? getTwoCharNick($보호입력대상) : '') ?: $보호입력대상;
  if ($보호입력대상 === $시전자닉 || $두글자 === $시전자닉) {
    $대상닉 = $시전자닉 !== '' ? $시전자닉 : $두글자;
  } else {
    $조회 = function_exists('회원정보_조회') ? 회원정보_조회($두글자) : [];
    if (empty($조회['name']) && $두글자 !== $보호입력대상 && function_exists('회원정보_조회')) {
      $조회 = 회원정보_조회($보호입력대상);
    }
    $대상닉 = trim((string)($조회['name'] ?? ''));
    if ($대상닉 === '') {
      $대상닉 = $두글자;
    }
  }
}

if (!isset($정보) || !is_array($정보)) {
  $정보 = [];
}
$내무기 = trim((string)($내무기 ?? ($정보['item'] ?? '')));
$내강화 = isset($내강화) ? (int)$내강화 : (int)($정보['enhance'] ?? 0);
$마법인가 = false;
if (function_exists('무기_마법인가') && $정보) {
  $마법인가 = 무기_마법인가($정보);
}
if (!$마법인가 && function_exists('마법_시전보호_공용무기인가')) {
  $마법인가 = 마법_시전보호_공용무기인가($내무기);
}
if (!$마법인가) {
  $마법인가 = ($내무기 === '🪄마법' || $내무기 === '🪄 마법' || mb_strpos($내무기, '마법') !== false);
}
if (!$마법인가) {
  시전_채팅응답('❌ 보호 부여는 마법 무기를 보유한 경우 가능');
}

$시전자_esc = addslashes($두자리닉넴);
$dur_row = db_select("SELECT durability FROM tb_member WHERE name = '{$시전자_esc}' LIMIT 1");
$durability_raw = $dur_row['durability'] ?? null;
$현재내구도 = ($durability_raw !== null) ? (int)$durability_raw : null;

if ($내강화 >= 10 && $현재내구도 !== null) {
  if ($현재내구도 <= 0) {
    시전_채팅응답("{$내무기} +{$내강화} 보호 사용!\n\n❌ 내구도 0 사용불가.");
  }
  if ($현재내구도 < $요청보호횟수) {
    시전_채팅응답("{$내무기} +{$내강화} 보호 사용!\n\n❌ 내구도 부족. (필요 {$요청보호횟수} · 현재 {$현재내구도})");
  }
}

$보호쿨타임 = isset($쿨타임) ? max(1, (int)$쿨타임) : 1;
$보호한도 = function_exists('마법_시전보호_공용_무료한도')
  ? 마법_시전보호_공용_무료한도($내무기, (int)$내강화)
  : (function_exists('무기_시전한도_3시간') ? 무기_시전한도_3시간($내무기, (int)$내강화) : 0);
if ($내강화 < 1 || $보호한도 <= 0) {
  시전_채팅응답('❌ 마법 1강 이상부터 보호 부여 가능');
}

if ($요청보호횟수 > 1 && function_exists('무기_시전_한도외배치_검증')) {
  $배치검증 = 무기_시전_한도외배치_검증($내무기, $내강화, $요청보호횟수, $두자리닉넴, $보호쿨타임, '보호');
  if (empty($배치검증['ok'])) {
    시전_채팅응답($배치검증['msg'] ?? '❌ 연속 보호 횟수를 확인해주세요.');
  }
}

$자숙위반 = function_exists('자숙_시전보호위반_적용') ? 자숙_시전보호위반_적용($두자리닉넴, '보호', $단위) : ['notice' => ''];
$자숙위반안내 = (string)($자숙위반['notice'] ?? '');

if (function_exists('마법_시전보호_공용한도_동기화')) {
  마법_시전보호_공용한도_동기화($두자리닉넴, $보호쿨타임);
}

$지금 = time();
$구간 = 무기_시전구간_적용($두자리닉넴, $보호쿨타임, true);
$구간시작 = $구간['window'] ?? date('Y-m-d H:i:s', $지금);
$사용횟수 = (int)($구간['used'] ?? 0);

$남은무료한도 = max(0, $보호한도 - $사용횟수);
if ($남은무료한도 <= 0) {
  $대상_esc = addslashes($대상닉);
  $대상정보 = db_select("SELECT protect FROM tb_member WHERE name = '{$대상_esc}' LIMIT 1");
  $대상보호 = (int)($대상정보['protect'] ?? 0);
  $다음리셋 = (int)($구간['reset_at'] ?? 0);
  if ($다음리셋 <= 0) {
    $다음리셋 = strtotime($구간시작) + ($보호쿨타임 * 3600);
  }
  $남은분 = (int)ceil(($다음리셋 - $지금) / 60);
  시전_채팅응답("❌ {$대상닉} 보호 {$대상보호} 한도 소진.\n1시간 시전·보호 공용 {$보호한도}회까지. {$남은분}분 후 초기화.");
}
if ($요청보호횟수 > $남은무료한도) {
  $요청보호횟수 = $남은무료한도;
}
$필요무료 = $요청보호횟수;

$대상_esc = addslashes($대상닉);
$멤버 = db_select("SELECT idx, protect FROM tb_member WHERE name = '{$대상_esc}' LIMIT 1");
if (empty($멤버['idx'])) {
  시전_채팅응답("❌ {$대상닉} 회원을 찾을 수 없어요.");
}
$지급결과 = function_exists('마법_보호_한도별_지급합계')
  ? 마법_보호_한도별_지급합계($내강화, $요청보호횟수)
  : ['amount' => max(1, (int)$내강화) * $요청보호횟수, 'crits' => 0, 'uses' => $요청보호횟수];
$지급보호 = max(0, (int)$지급결과['amount']);
$크리횟수 = (int)($지급결과['crits'] ?? 0);
$새보호 = (int)($멤버['protect'] ?? 0) + $지급보호;
db_query("UPDATE tb_member SET protect = {$새보호} WHERE name = '{$대상_esc}'");
if ($내강화 >= 10 && $현재내구도 !== null) {
  db_query("UPDATE tb_member SET durability = GREATEST(IFNULL(durability, 0) - {$요청보호횟수}, 0) WHERE name = '{$시전자_esc}'");
}
if ($필요무료 > 0) {
  db_query("UPDATE tb_member SET magic_used = magic_used + {$필요무료} WHERE name = '{$시전자_esc}'");
  $사용횟수 += $필요무료;
}
$남은횟수 = max(0, $보호한도 - $사용횟수);

db_query("INSERT INTO tb_damege SET 공격자 = '{$시전자_esc}', 피해자 = '{$대상_esc}', 유형 = '보호', 피해 = '{$지급보호}', regdate = NOW()");
$한도표시 = "한도 {$요청보호횟수}";
if ($크리횟수 > 0) {
  $한도표시 .= " · 크{$크리횟수}";
}
$보호머리 = ($요청보호횟수 === 1 && $크리횟수 > 0) ? '💥크리' : '🛡️';
$대상표시 = ($대상닉 === $시전자닉) ? "본인({$대상닉})" : $대상닉;
$결과멘트 = $자숙위반안내."{$보호머리} {$대상표시} 보호 +{$지급보호} (현재 {$새보호})\n({$한도표시} · 시전·보호 공용 남은 {$남은횟수}/{$보호한도})";
시전_채팅응답($결과멘트);
