<?php
/**
 * 지또 당첨 세금 — 보유 냥 구간별 세율
 * - 10억 단위로 0.5%씩 증가
 * - 최저: 10억 미만 = 0.5%
 * - 상한: 300억 이상 = 15.5% (그 이상은 모두 15.5%)
 *
 * 예시
 *   5억   → 0.5%
 *   10억  → 1%
 *   20억  → 1.5%
 *   30억  → 2%
 *   100억 → 5.5%
 *   200억 → 10.5%
 *   300억 → 15.5% (상한)
 *   500억 → 15.5% (상한 유지)
 */
function 지또_보유기준_세율비율($내포인트) {
    $내포인트   = (int)$내포인트;
    $십억      = 1000000000;          // 10억
    $상한_보유  = 30000000000;         // 300억
    $상한_세율  = 0.155;               // 15.5%
    $최저_세율  = 0.005;               // 0.5%

    if ($내포인트 <= 0) {
        return $최저_세율;
    }

    if ($내포인트 >= $상한_보유) {
        return $상한_세율;
    }

    // 10억 단위 구간 (floor 기반): 0~10억 미만 = 1단계 = 0.5%
    // 10억~20억 미만 = 2단계 = 1%, 20억~30억 미만 = 3단계 = 1.5%, ...
    $단계 = (int)floor($내포인트 / $십억) + 1;
    return $단계 * 0.005;
}

function 지또_보유기준_세율표시문자열($내포인트) {
    $r = 지또_보유기준_세율비율($내포인트);
    if ($r <= 0) {
        return '0%';
    }
    // 0.5% 단위 표시 (예: 1%, 1.5%, 2%, ...)
    $pct = round($r * 100, 1);
    if (abs($pct - round($pct)) < 0.001) {
        return (string)(int)round($pct) . '%';
    }
    return rtrim(rtrim(number_format($pct, 1, '.', ''), '0'), '.') . '%';
}
