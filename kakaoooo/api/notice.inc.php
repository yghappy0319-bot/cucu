if (!function_exists('공지_확인_처리')) {
  function 공지_확인_처리($두자리닉넴) {
    $닉 = trim((string)$두자리닉넴);
    if ($닉 === '') {
      echo 전송("회원 정보를 찾을 수 없어요.");
      exit;
    }
    $닉_esc = addslashes($닉);
    $회원 = db_select("SELECT idx, notichk FROM tb_member WHERE name = '{$닉_esc}' LIMIT 1");
    if (empty($회원['idx'])) {
      echo 전송("회원 정보를 찾을 수 없어요.");
      exit;
    }

    if (function_exists('미션완료_기록_if_new')) {
      미션완료_기록_if_new($닉, '공지', '공지끝까지읽기', true);
    }

    if ((int)$회원['notichk'] === 0) {
      // 전체 게임냥(시세 기준)의 10%
      $지급 = function_exists('전체냥기준금액') ? 전체냥기준금액(10) : '1';
      $지급 = function_exists('냥_정수문자열') ? 냥_정수문자열($지급) : (string)$지급;
      if ($지급 === '' || $지급 === '0') {
        $지급 = '1';
      }
      $지급_sql = function_exists('냥_SQL정수') ? 냥_SQL정수($지급) : preg_replace('/\D+/', '', $지급);
      if ($지급_sql === '' || $지급_sql === '0') {
        $지급_sql = '1';
        $지급 = '1';
      }
      db_query("UPDATE tb_member SET point = point + {$지급_sql}, notichk = 1 WHERE idx = {$회원['idx']} LIMIT 1");
      $지급표시 = function_exists('랭킹_게임냥표시')
        ? 랭킹_게임냥표시($지급, '냥')
        : (number_format((float)$지급) . '냥');
      echo 전송("{$닉} 공지 확인 완료🎉 (전체 게임냥 10% · {$지급표시} 지급)");
    } else {
      echo 전송("{$닉} 이미 공지 확인 완료");
    }
    exit;
  }
}
